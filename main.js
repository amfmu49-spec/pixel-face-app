let avatarCanvas, ctx;
let obsCanvas, obsCtx;
let lastTime = 0;
let bounceOffset = 0;

function initCanvas() {
  avatarCanvas = document.getElementById('avatar-canvas');
  ctx = avatarCanvas.getContext('2d');
  
  obsCanvas = document.getElementById('obs-avatar-canvas');
  obsCtx = obsCanvas.getContext('2d');

  // Disable smoothing for sharp pixels
  ctx.imageSmoothingEnabled = false;
  obsCtx.imageSmoothingEnabled = false;

  requestAnimationFrame(renderLoop);
}

function renderLoop(time) {
  const dt = time - lastTime;
  lastTime = time;

  // Bounce animation calculation
  if (state.bounceEnabled) {
    bounceOffset = Math.sin(time * 0.003) * 6;
  } else {
    bounceOffset = 0;
  }

  // Demo Talking Loop
  if (state.isDemoTalking) {
    const talkCycle = (time % 600) / 600;
    if (talkCycle < 0.2) state.mouthState = 'closed';
    else if (talkCycle < 0.4) state.mouthState = 'A';
    else if (talkCycle < 0.6) state.mouthState = 'I';
    else if (talkCycle < 0.8) state.mouthState = 'O';
    else state.mouthState = 'U';
  }

  // Draw Avatar onto main canvas & OBS canvas
  drawAvatar(ctx, avatarCanvas.width, avatarCanvas.height);
  drawAvatar(obsCtx, obsCanvas.width, obsCanvas.height);

  requestAnimationFrame(renderLoop);
}

function drawAvatar(c, width, height) {
  c.clearRect(0, 0, width, height);

  // Background Mode
  if (state.bgMode === 'green') {
    c.fillStyle = '#00ff00';
    c.fillRect(0, 0, width, height);
  } else if (state.bgMode === 'blue') {
    c.fillStyle = '#0000ff';
    c.fillRect(0, 0, width, height);
  } else if (state.bgMode === 'dark') {
    c.fillStyle = PALETTES[state.paletteName].bg;
    c.fillRect(0, 0, width, height);
  } // transparent does nothing

  const pixelSize = Math.floor(width / GRID_SIZE);
  const startX = 0;
  const startY = Math.round(bounceOffset);

  const palette = PALETTES[state.paletteName];

  // Helper to resolve pixel color code to RGB hex
  function getColor(code) {
    switch (code) {
      case 1: return palette.skinBorder;
      case 2: return palette.skin;
      case 3: return palette.eye;
      case 4: return palette.mouth;
      case 5: return palette.acc;
      case 6: return '#ffffff';
      default:
        // Handle hex string if edited by pixel editor
        if (typeof code === 'string' && code.startsWith('#')) return code;
        return null;
    }
  }

  // Render Grid Layers
  const layers = [
    state.baseGrid,
    getEyeGridForCurrentState(),
    getMouthGridForCurrentState(),
    state.accGrid
  ];

  c.save();

  // Glow Effect
  if (state.glowEnabled) {
    c.shadowColor = palette.eyeGlow;
    c.shadowBlur = 12;
  }

  for (let r = 0; r < GRID_SIZE; r++) {
    for (let col = 0; col < GRID_SIZE; col++) {
      for (const layer of layers) {
        if (!layer) continue;
        const val = layer[r][col];
        if (val !== 0) {
          const color = getColor(val);
          if (color) {
            c.fillStyle = color;
            c.fillRect(
              startX + col * pixelSize, 
              startY + r * pixelSize, 
              pixelSize, 
              pixelSize
            );
          }
        }
      }
    }
  }

  c.restore();

  // Optional Dot Grid Lines
  if (state.gridEnabled) {
    c.strokeStyle = palette.grid;
    c.lineWidth = 1;
    for (let i = 0; i <= GRID_SIZE; i++) {
      c.beginPath();
      c.moveTo(i * pixelSize, 0);
      c.lineTo(i * pixelSize, height);
      c.stroke();

      c.beginPath();
      c.moveTo(0, i * pixelSize);
      c.lineTo(width, i * pixelSize);
      c.stroke();
    }
  }
}

