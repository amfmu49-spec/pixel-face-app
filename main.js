// ------------------------------------------------------------
// 2. DEFAULT PIXEL ART GRID TEMPLATES (24x24 Grid)
// ------------------------------------------------------------
const GRID_SIZE = 24;

// Helper to create empty 24x24 matrix
function createEmptyGrid() {
  return Array(GRID_SIZE).fill(null).map(() => Array(GRID_SIZE).fill(0));
}

// Convert ASCII pattern string to 24x24 grid
function parsePattern(asciiStr, charMap) {
  const grid = createEmptyGrid();
  const lines = asciiStr.trim().split('\n').map(l => l.trim());
  for (let r = 0; r < Math.min(lines.length, GRID_SIZE); r++) {
    for (let c = 0; c < Math.min(lines[r].length, GRID_SIZE); c++) {
      const char = lines[r][c];
      grid[r][c] = charMap[char] || 0;
    }
  }
  return grid;
}

