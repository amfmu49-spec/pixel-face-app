async function toggleMicrophone() {
  const btn = document.getElementById('btn-toggle-mic');
  const hudStatus = document.getElementById('hud-status');

  if (state.isMicActive) {
    // Stop Microphone
    if (state.micStream) {
      state.micStream.getTracks().forEach(track => track.stop());
    }
    state.isMicActive = false;
    btn.innerHTML = '<span class="mic-icon">🎙️</span> マイクを開始';
    btn.classList.remove('btn-primary');
    btn.classList.add('btn-primary');
    hudStatus.textContent = 'マイク: 停止中';
    state.mouthState = 'closed';
    return;
  }

  try {
    const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    state.micStream = stream;
    state.audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    const source = state.audioCtx.createMediaStreamSource(stream);
    
    state.analyser = state.audioCtx.createAnalyser();
    state.analyser.fftSize = 512;
    source.connect(state.analyser);

    state.isMicActive = true;
    btn.innerHTML = '<span class="mic-icon">🛑</span> マイクを停止';
    btn.classList.remove('btn-primary');
    btn.classList.add('btn-danger');
    hudStatus.textContent = 'マイク: 動作中';

    processAudio();

  } catch (err) {
    alert('マイクの取得に失敗しました。マイクのアクセス許可を確認してください。');
    console.error(err);
  }
}

function processAudio() {
  if (!state.isMicActive || !state.analyser) return;

  const dataArray = new Uint8Array(state.analyser.frequencyBinCount);
  state.analyser.getByteFrequencyData(dataArray);

  // Calculate Volume (RMS)
  let sum = 0;
  for (let i = 0; i < dataArray.length; i++) {
    sum += dataArray[i] * dataArray[i];
  }
  const rms = Math.sqrt(sum / dataArray.length);
  const rawVolPercent = Math.min(100, Math.round((rms / 128) * 100 * state.sensitivity));

  // Update Meter UI
  const volBar = document.getElementById('vol-bar');
  const volVal = document.getElementById('vol-value');
  volBar.style.width = `${rawVolPercent}%`;
  volVal.textContent = `${rawVolPercent}%`;

  // Check Silence Threshold
  if (rawVolPercent < state.threshold) {
    state.mouthState = 'closed';
    updateVowelsUI('closed');
  } else {
    // Frequency spectral analysis for Japanese Vowel Detection
    // Low: 100-500Hz, Mid: 500-1500Hz, High: 1500-4000Hz
    const lowEnergy = getEnergyRange(dataArray, 2, 10);
    const midEnergy = getEnergyRange(dataArray, 10, 30);
    const highEnergy = getEnergyRange(dataArray, 30, 80);

    let detectedVowel = 'A';

    if (highEnergy > midEnergy && highEnergy > lowEnergy) {
      detectedVowel = 'I'; // 'い' (High frequency emphasis)
    } else if (lowEnergy > midEnergy * 1.3) {
      detectedVowel = 'U'; // 'う' (Deep low frequency)
    } else if (midEnergy > lowEnergy && midEnergy > highEnergy) {
      detectedVowel = 'O'; // 'お' (Mid range emphasis)
    } else if (rawVolPercent > 50) {
      detectedVowel = 'A'; // 'あ' (Wide open)
    } else {
      detectedVowel = 'E'; // 'え'
    }

    state.mouthState = detectedVowel;
    updateVowelsUI(detectedVowel);
  }

  requestAnimationFrame(processAudio);
}

function getEnergyRange(array, startBin, endBin) {
  let total = 0;
  for (let i = startBin; i < endBin && i < array.length; i++) {
    total += array[i];
  }
  return total / (endBin - startBin);
}

function updateVowelsUI(activeVowel) {
  const vowels = ['a', 'i', 'u', 'e', 'o'];
  vowels.forEach(v => {
    const el = document.getElementById(`vowel-${v}`);
    if (v.toUpperCase() === activeVowel) {
      el.classList.add('active');
    } else {
      el.classList.remove('active');
    }
  });
}

