function getEyeGridForCurrentState() {
  if (state.isBlinking) {
    return parsePattern(EYES_BLINK, CHAR_MAP);
  }

  switch (state.currentExpression) {
    case 'smile': return parsePattern(EYES_SMILE, CHAR_MAP);
    case 'surprised': return parsePattern(EYES_SURPRISED, CHAR_MAP);
    case 'wink': return parsePattern(EYES_WINK, CHAR_MAP);
    case 'angry': return parsePattern(EYES_ANGRY, CHAR_MAP);
    case 'sad': return parsePattern(EYES_ANGRY, CHAR_MAP);
    case 'sleep': return parsePattern(EYES_SLEEP, CHAR_MAP);
    case 'cool': return parsePattern(EYES_COOL, CHAR_MAP);
    case 'neutral':
    default:
      return state.eyesGrid || parsePattern(EYES_NORMAL, CHAR_MAP);
  }
}

function getMouthGridForCurrentState() {
  switch (state.mouthState) {
    case 'A': return parsePattern(MOUTH_A, CHAR_MAP);
    case 'I': return parsePattern(MOUTH_I, CHAR_MAP);
    case 'U': return parsePattern(MOUTH_U, CHAR_MAP);
    case 'E': return parsePattern(MOUTH_E, CHAR_MAP);
    case 'O': return parsePattern(MOUTH_O, CHAR_MAP);
    case 'closed':
    default:
      return state.mouthClosedGrid || parsePattern(MOUTH_CLOSED, CHAR_MAP);
  }
}

